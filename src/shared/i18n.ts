export const dictionaries = { de, en } as const;
export type Language = keyof typeof dictionaries;

let language: Language = 'en';

export function setLanguage(next: Language): void {
  language = next;
}

export function tr(lang: Language, key: string, vars: Record<string, string | number> = {}): string {
  const text = (dictionaries[lang] as Record<string, string>)[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => String(vars[name] ?? match));
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return tr(language, key, vars);
}
